<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require_once __DIR__ . '/../php/homepage_assets.php';
$root = dirname(__DIR__) . '/';
$manifest = [];
foreach (HomepageStyleSources() as $group => $sources) {
    $bundle = "/* Generated by scripts/build_homepage_styles.php; edit the source styles. */\n";
    $manifest[$group] = ['sources' => []];
    foreach ($sources as $source) {
        $text = str_replace("\r\n", "\n", (string)file_get_contents($root . $source));
        $manifest[$group]['sources'][$source] = hash('sha256', $text);
        $bundle .= "\n/* Source: " . $source . " */\n" . $text . "\n";
    }
    $manifest[$group]['bundle'] = hash('sha256', $bundle);
    file_put_contents($root . 'styles/homepage-' . $group . '.bundle.css', $bundle);
}
file_put_contents($root . 'styles/homepage-styles.manifest.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo "Built two homepage style groups in original cascade order.\n";
