<?php
declare(strict_types=1);
if (PHP_SAPI !== 'cli') { http_response_code(404); exit; }
require_once __DIR__ . '/../php/homepage_assets.php';
$root = dirname(__DIR__) . '/';
$bundle = "/* Generated by scripts/build_homepage_runtime.php. Edit the source files. */\n";
$manifest = ['sources' => []];
foreach (HomepageRuntimeSources() as $source) {
    $text = str_replace("\r\n", "\n", (string)file_get_contents($root . $source));
    $manifest['sources'][$source] = hash('sha256', $text);
    $bundle .= "\n;/* Source: " . $source . " */\n" . $text . "\n";
}
$manifest['bundle'] = hash('sha256', $bundle);
file_put_contents($root . 'js/homepage-runtime.bundle.js', $bundle);
file_put_contents($root . 'js/homepage-runtime.manifest.json', json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
echo 'Built homepage runtime from ' . count($manifest['sources']) . " sources.\n";
